"""DA005 research dashboard: honest dataset exploration and baseline results."""
import json
from pathlib import Path

import streamlit as st

from src.da005.dataset import DatasetValidationError, ROOT, load_split, summarize

st.set_page_config(page_title="DA005 | Mini-SIEM Lab", page_icon=None, layout="wide")
st.title("DA005 · Mini-SIEM Lab")
st.caption("Research prototype | UNSW-NB15 network-flow dataset | TDTU")
st.warning(
    "Historical, labelled network flows. This dashboard is NOT a live SIEM/SOC, "
    "and ground-truth labels are NOT AI predictions."
)

split = st.sidebar.selectbox("Dataset partition", ["test", "train"])
limit = st.sidebar.select_slider("Rows to explore", options=[1000, 5000, 10000, 25000, 50000], value=10000)
st.sidebar.caption("The fixed test split is reserved for final model evaluation.")


@st.cache_data(show_spinner="Reading validated dataset...")
def get_data(partition: str, rows: int):
    return load_split(partition, limit=rows)


try:
    frame = get_data(split, limit)
    profile = summarize(frame)
except (FileNotFoundError, DatasetValidationError, ValueError) as exc:
    st.error(str(exc))
    st.info("Run: python scripts/download_unsw_nb15.py")
    st.stop()

a, b, c = st.columns(3)
a.metric("Flows sampled", f"{profile['rows']:,}")
b.metric("Normal (ground truth)", f"{profile['normal']:,}")
c.metric("Attack (ground truth)", f"{profile['attack']:,}")

explore, model_tab, soc_tab = st.tabs(["Traffic explorer", "AI evaluation", "SOC workflow"])

with explore:
    st.subheader("Attack categories (ground truth)")
    st.bar_chart(profile["attack_categories"], horizontal=True)
    category = st.selectbox("Filter attack category", ["All"] + sorted(profile["attack_categories"]))
    shown = frame if category == "All" else frame[frame["attack_cat"] == category]
    st.dataframe(shown.head(300), use_container_width=True, hide_index=True)
    st.caption("Up to 300 rows shown. Sample is first N rows of the selected official partition.")

with model_tab:
    metrics_path = ROOT / "reports" / "baseline_metrics.json"
    if metrics_path.is_file():
        try:
            metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
            if not isinstance(metrics, dict) or "metrics" not in metrics:
                raise ValueError("Invalid baseline metrics structure")
            st.success("Baseline evaluation report found.")
            st.json(metrics, expanded=False)
            st.caption("Metrics generated by scripts/evaluate_unsw_nb15.py on the official test partition.")
        except (OSError, ValueError, json.JSONDecodeError) as exc:
            st.error(f"Cannot read evaluation report: {exc}")
    else:
        st.info("No measured baseline yet. Run: python scripts/evaluate_unsw_nb15.py")
        st.caption("No accuracy, F1 or alerts are fabricated for this prototype.")

with soc_tab:
    st.info("SOC alert queue and incident triage are planned, not yet implemented.")
    st.markdown(
        "Next milestone: persist actual model predictions, attach model version "
        "and evidence to alerts, then implement analyst triage states."
    )
